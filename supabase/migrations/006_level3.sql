-- 精简本语法章是「单句」，不是分开的「句型」「句类」。补上这一节，排在「复句」前面
update public.knowledge_points as child
set sort_order = child.sort_order + 1
from public.knowledge_points as chapter
where child.parent_id = chapter.id
  and chapter.parent_id is null
  and chapter.name = '语法'
  and child.sort_order >= 8
  and not exists (
    select 1 from public.knowledge_points existing
    where existing.parent_id = chapter.id and existing.name = '单句'
  );

