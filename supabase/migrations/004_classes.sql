-- =====================================================================
-- 班级表（兼容已手动创建的 classes 表：id 为整数自增、name、created_at）
-- + profiles 增加班级字段 + 注册触发器读取元数据 + RLS
-- 在 SQL Editor 中整体执行（可重复执行）
-- =====================================================================

-- 若表尚不存在则创建；已存在则跳过，后面用 alter 补齐列
create table if not exists public.classes (
  id         bigint generated by default as identity primary key,
  name       text not null,
  created_at timestamptz not null default now()
);

alter table public.classes
  add column if not exists sort_order int not null default 0,
  add column if not exists created_by uuid references public.profiles (id) on delete set null;

-- 班级名称唯一
do $$ begin
  alter table public.classes add constraint classes_name_key unique (name);
exception when duplicate_table or duplicate_object then null; end $$;

-- profiles 增加班级字段（类型与 classes.id 一致）
alter table public.profiles
  add column if not exists class_id   bigint references public.classes (id) on delete set null,
  add column if not exists class_name text;

create index if not exists profiles_class_idx on public.profiles (class_id);

-- 注册时从 auth 元数据写入 姓名 / 学号 / 班级
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  insert into public.profiles (id, display_name, student_no, class_id, class_name)
  values (
    new.id,
    coalesce(nullif(meta ->> 'display_name', ''), split_part(new.email, '@', 1)),
    nullif(meta ->> 'student_no', ''),
    nullif(meta ->> 'class_id', '')::bigint,
    nullif(meta ->> 'class_name', '')
  )
  on conflict (id) do update
    set display_name = excluded.display_name,
        student_no   = coalesce(excluded.student_no, public.profiles.student_no),
        class_id     = coalesce(excluded.class_id, public.profiles.class_id),
        class_name   = coalesce(excluded.class_name, public.profiles.class_name);
  return new;
end $$;

-- ---------- RLS ----------
alter table public.classes enable row level security;

-- 注册页在登录前就要读班级列表，因此匿名也可读
drop policy if exists "classes: anyone reads" on public.classes;
create policy "classes: anyone reads"
  on public.classes for select to anon, authenticated using (true);

drop policy if exists "classes: teacher writes" on public.classes;
create policy "classes: teacher writes"
  on public.classes for all to authenticated
  using (public.is_teacher()) with check (public.is_teacher());
